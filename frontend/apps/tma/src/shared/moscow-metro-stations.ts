function isMoscow(city: string): boolean {
	const normalized = city.trim().toLocaleLowerCase('ru-RU')
	return !normalized || normalized === 'москва' || normalized === 'moscow'
}

/**
 * Для Москвы возвращает полный справочник, для остальных городов — станции
 * из анкет. Значение активного фильтра всегда сохраняется в списке.
 */
export function mergeMetroStationOptions(
	profileStations: Iterable<string>,
	city: string,
	selectedStation = '',
): string[] {
	const stations = new Set<string>(
		isMoscow(city) ? MOSCOW_METRO_STATIONS : [],
	)

	for (const station of profileStations) {
		const normalized = station.trim().replace(/^м\.\s*/i, '')
		if (normalized) stations.add(normalized)
	}

	const selected = selectedStation.trim().replace(/^м\.\s*/i, '')
	if (selected) stations.add(selected)

	return Array.from(stations).sort((left, right) =>
		left.localeCompare(right, 'ru-RU'),
	)
}
